/** Bytes from disk instead of S3 — the one stand-in in this measurement. */
function storeOf(bytes: Buffer): DocumentStore {
  return { get: () => Promise.resolve(bytes) } as unknown as DocumentStore;
}

/** Case/punctuation-tolerant supplier compare: "Wolseley UK Ltd" matches "Wolseley". */
function supplierMatches(read: string | null, gold: string): boolean {
  if (read === null) return false;
  const norm = (v: string) => v.toLowerCase().replace(/\b(ltd|limited|co|uk|plc)\b/g, '').replace(/[^a-z0-9]/g, '');
  return norm(read).includes(norm(gold)) || norm(gold).includes(norm(read));
}

/** A credit note read as a magnitude with docType CREDIT_NOTE counts as read: the sign is the type. */
function moneyMatches(read: number | null, gold: number, docType: string): boolean {
  if (read === null) return false;
  if (read === gold) return true;
  return gold < 0 && docType === 'CREDIT_NOTE' && read === Math.abs(gold);
}

function referenceMatches(read: string | null, gold: string | null): boolean {
  if (gold === null) return true; // the document carries none; anything the model offers is not scored
  if (read === null) return false;
  return read.replace(/\s/g, '').toLowerCase().includes(gold.replace(/\s/g, '').toLowerCase());
}

interface Row {
  readonly file: string;
  readonly corpus: 'pdf' | 'image';
  readonly ok: boolean;
  readonly fields: Readonly<Record<'supplier' | 'date' | 'total' | 'vat' | 'reference', boolean>> | null;
  readonly detail: string;
}

function score(gold: Gold, doc: ExtractedDocument): Row['fields'] {
  return {
    supplier: supplierMatches(doc.supplierName, gold.supplier),
    date: doc.documentDate === gold.date,
    total: moneyMatches(doc.totalPence, gold.totalPence, doc.docType),
    vat: moneyMatches(doc.taxPence, gold.taxPence, doc.docType),
    reference: referenceMatches(doc.reference, gold.reference),
  };
}

async function main(): Promise<void> {
  process.stdout.write(`\nExtraction accuracy probe — walkthrough finding 7\n`);
  process.stdout.write(`  model   ${MODELS[TASKS.extractionVisionFirst.model]}\n`);
  process.stdout.write(`  region  ${REGION}\n`);
  process.stdout.write(`  corpus  ${GOLD.length} documents · 5 fields each · gold from docs/testing/gpt-test-document-prompts.md §9\n\n`);

  const rows: Row[] = [];
  for (const gold of GOLD) {
    const bytes = readFileSync(resolve(FIXTURES, gold.file));
    const budget = new InMemoryAiBudget(1_000_000);
    const client = new AnthropicBedrock({ awsRegion: REGION, maxRetries: 1 });
    const extractor = new BedrockExtractor({
      store: storeOf(bytes),
      region: REGION,
      budget,
      client: { messages: { create: client.messages.create.bind(client.messages) } } as unknown as Pick<AnthropicBedrock, 'messages'>,
    });
    process.stdout.write(`reading ${gold.file}...\n`);
    const outcome = await extractor.extract({
      filename: gold.file,
      byteHash: 'accuracy-probe',
      s3Key: 'accuracy-probe',
      mimeType: gold.mimeType,
      practiceId: 'measure',
    });
    if (!outcome.ok) {
      rows.push({ file: gold.file, corpus: gold.corpus, ok: false, fields: null, detail: `${outcome.failure.code} ${outcome.failure.message}` });
    } else {
      const d = outcome.document;
      rows.push({
        file: gold.file,
        corpus: gold.corpus,
        ok: true,
        fields: score(gold, d),
        detail: `read supplier=${d.supplierName} date=${d.documentDate} total=${d.totalPence} vat=${d.taxPence} ref=${d.reference} type=${d.docType}`,
      });
    }
    await sleep(400);
  }

  process.stdout.write('\nfile                                       supplier date total vat ref\n');
  for (const row of rows) {
    if (row.fields === null) {
      process.stdout.write(`${row.file.padEnd(42)} FAILED — ${row.detail}\n`);
      continue;
    }
    const mark = (v: boolean) => (v ? '  ✓  ' : '  ✗  ');
    process.stdout.write(
      `${row.file.padEnd(42)}${mark(row.fields.supplier)}${mark(row.fields.date)}${mark(row.fields.total)}${mark(row.fields.vat)}${mark(row.fields.reference)}\n`,
    );
    process.stdout.write(`  ${row.detail}\n`);
  }

  const tally = (subset: readonly Row[]): string => {
    const scored = subset.filter((r) => r.fields !== null);
    const checks = scored.flatMap((r) => Object.values(r.fields ?? {}));
    const hits = checks.filter(Boolean).length;
    return `${hits}/${checks.length} fields (${checks.length === 0 ? '—' : `${((hits / checks.length) * 100).toFixed(1)}%`}) over ${scored.length} read + ${subset.length - scored.length} failed docs`;
  };
  process.stdout.write(`\nborn-digital PDFs (pixels ARE the prompt): ${tally(rows.filter((r) => r.corpus === 'pdf'))}\n`);
  process.stdout.write(`generated images (adjudicate ✗ by eye):    ${tally(rows.filter((r) => r.corpus === 'image'))}\n`);
  process.stdout.write(`whole corpus:                              ${tally(rows)}\n\n`);
  process.stdout.write('⚠ n is small, the corpus is synthetic, and image-row misses may be the image\n');
  process.stdout.write('generator rather than the extractor. This replaces an invented number with a\n');
  process.stdout.write('taken one; it is not a calibration. Nothing here justifies quoting 98%.\n\n');
}

main().catch((error: unknown) => {
  process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
  process.exitCode = 1;
});
