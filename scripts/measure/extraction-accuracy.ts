/**
 * Measure per-field extraction ACCURACY against the synthetic gold manifest
 * (4 Sep 2026, walkthrough finding 7).
 *
 * ## Why this exists
 *
 * "Confidence up to 98%" was said out loud with no mechanical embodiment behind
 * it: the confidence-threshold seam is deliberately empty (eval-calibrated,
 * does not exist yet), and the only accuracy figures on record were research
 * numbers about CATEGORISATION (~62.5–79%, `docs/research/business-types-and-
 * accounts.md`), not a measurement of what the pinned extractor reads. A claim
 * with no way to re-take it decays into folklore — the same argument as
 * `extraction-cost.ts` beside this file, which is also this script's chassis.
 *
 * ## What it measures, and what it deliberately does not
 *
 * The REAL `BedrockExtractor` — production class, real system prompt, real
 * forced tool call, the model pinned in `chat-framework/models.ts` — against
 * the synthetic corpus in `fixtures/synthetic/`, scored per field against the
 * expected-values manifest in `docs/testing/gpt-test-document-prompts.md` §9.
 * Five fields per document: supplier, date, total, VAT, reference.
 *
 * ⚠ **The gold table describes the PROMPTS, not necessarily the PIXELS.** The
 * image fixtures were generated by an image model, which mangles digits, so a
 * mismatch on an image fixture means ONE OF: the extractor misread, or the
 * generator mis-rendered. The verdict column says which corpus class the
 * document is (`pdf` = born-digital, the pixels ARE the prompt; `image` =
 * generated, adjudicate by eye before blaming the extractor). Do not quote the
 * image-row failures as extraction errors without looking at the image.
 *
 * ⚠ **n is small.** Nine documents, forty-five field reads. This is a smoke
 * measurement that replaces an invented number with a taken one; it is not a
 * calibration corpus. Growing `evals/` a real extraction dataset is still owed
 * (its README says so in as many words).
 *
 * ## Running it
 *
 *   pnpm tsx scripts/measure/extraction-accuracy.ts
 *
 * Spends real money — nine model calls, ~10–15p total — against whatever AWS
 * credentials the environment resolves. Re-run whenever the model pin, prompt
 * or tool schema moves. The HTML fixtures must first be printed to PDF
 * (playwright `page.pdf`); the PNG fixtures are used as they are.
 */

